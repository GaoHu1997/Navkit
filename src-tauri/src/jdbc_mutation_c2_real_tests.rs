//! Opt-in REAL Rust C2 service -> framed Java -> official embedded H2 tests.
//! These exercise the production backend dispatcher and the shared opaque
//! Registry, not a fake adapter, desktop Window IPC or another JDBC product.
use super::*;
use crate::{db::Db, http_db::{HttpAdapter, HttpDb}, models::{ConnectionRequest, DbKind}, mutation};

const PRINCIPAL: &str = "isolated-c2-window";
const OWNER: &str = "isolated-c2-grid";
struct Fixture { db: std::sync::Arc<Db>, kind: DbKind, runtime: crate::db::runtime::RuntimeRegistry, fingerprint: String }
impl Fixture {
    fn http(&self) -> &HttpDb { let Db::Http(http) = self.db.as_ref() else { panic!("real JDBC adapter required") }; http }
    async fn sql(&self, sql: &str) -> crate::http_db::HttpRows { self.http().run("PUBLIC", "", sql).await.unwrap() }
    fn draft(&self, table: &str, kind: &str, keys: Pairs, old: Pairs, changes: Pairs) -> MutationDraft {
        MutationDraft { connection_id: "isolated-c2-connection".into(), owner_id: OWNER.into(), schema: "PUBLIC".into(),
            table: table.into(), kind: kind.into(), keys, original_values: old, changes }
    }
    async fn preview(&self, draft: &MutationDraft) -> PlanInternal {
        assert!(self.runtime.matches("isolated-c2-connection", &self.fingerprint, &self.db));
        mutation::prepare_plan(&self.db, &self.kind, draft, PRINCIPAL, self.fingerprint.clone()).await.unwrap()
    }
    async fn submit(&self, registry: &mutation::Registry, id: &str) -> MutationReceipt {
        let plan = registry.take(id, PRINCIPAL, OWNER).unwrap();
        assert!(registry.take(id, PRINCIPAL, OWNER).is_err(), "same Registry consumes exactly once before sending");
        assert!(self.runtime.matches("isolated-c2-connection", &plan.endpoint_fingerprint, &self.db));
        mutation::validate_plan_context(&self.db, &plan).await.unwrap();
        mutation::execute_plan(&self.db, &self.kind, id, &plan, false, 10).await.unwrap()
    }
}
async fn new_fixture(generic: bool, compatibility: bool) -> Fixture {
    let root = crate::storage::portable_root();
    assert!(root.starts_with(std::env::temp_dir()) && root.file_name().unwrap().to_string_lossy().starts_with("navkit-pl20-c2-tests-"),
        "C2 real tests must use a copied executable in a private OS temp root, never user storage");
    let jar = std::env::var("NAVKIT_H2_JAR").expect("official H2 2.3.232 required; absence is NOT VERIFIED");
    // A native kind label must not turn a real JDBC physical adapter into SQLx.
    let kind = DbKind::of(if generic { "sqlite" } else { "h2" });
    let request = ConnectionRequest { kind: kind.clone(), host: String::new(), port: 0, user: "sa".into(), password: String::new(),
        database: format!("jdbc:h2:mem:c2_{};DB_CLOSE_DELAY=-1{}", uuid::Uuid::new_v4().simple(), if compatibility { ";MODE=MySQL" } else { "" }),
        file: String::new(), params: serde_json::json!({"h2_jar": jar}).to_string(), timeout_secs: 30 };
    let adapter: Box<dyn HttpAdapter> = if generic {
        Box::new(crate::jdbc_db::JdbcDb::connect(&request, &jar, &request.database, "org.h2.Driver").await.unwrap())
    } else { Box::new(crate::h2_db::H2Db::connect(&request).await.unwrap()) };
    let cfg = crate::db::runtime::request_config("isolated-c2-connection", &request, false, false);
    let fingerprint = crate::db::runtime::binding_fingerprint(&cfg).unwrap();
    let db = std::sync::Arc::new(Db::Http(HttpDb::from_adapter(&request, adapter).await.unwrap()));
    let runtime = crate::db::runtime::RuntimeRegistry::default();
    runtime.publish(&cfg.id, &fingerprint, &db, None, crate::db::runtime::keepalive_policy(&cfg).unwrap()).unwrap();
    assert!(runtime.matches(&cfg.id, &fingerprint, &db), "only the actually opened Arc may receive its real configuration fingerprint");
    assert!(!runtime.matches(&cfg.id, "changed-endpoint", &db), "never attach a changed configuration fingerprint to an old Arc");
    Fixture { db, kind, runtime, fingerprint }
}
fn identity(id: &str) -> Pairs { vec![("ID".into(), DbValue::Integer(id.into()))] }
fn text(name: &str, value: &str) -> (String, DbValue) { (name.into(), DbValue::Text(value.into())) }
fn integer(name: &str, value: &str) -> (String, DbValue) { (name.into(), DbValue::Integer(value.into())) }
fn app_code(error: anyhow::Error) -> String { AppError::from(error).code }

async fn exercise(generic: bool) {
    let fixture = new_fixture(generic, false).await;
    let caps = fixture.http().relational_capabilities().await.unwrap();
    assert_eq!(caps.product, "H2"); assert!(caps.row_write && caps.metadata && !caps.ddl_write);
    fixture.sql("CREATE TABLE C2_TYPED(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,BIG BIGINT NOT NULL,AMT DECIMAL(38,12) NOT NULL,TXT VARCHAR(100),NIL VARCHAR(20),EMPTY VARCHAR(20),BIN VARBINARY(64),D DATE,TM TIME(9),TS TIMESTAMP(9),TZ TIMESTAMP(9) WITH TIME ZONE,U UUID,Q INTEGER DEFAULT 7 NOT NULL CHECK(Q>=0),G INTEGER GENERATED ALWAYS AS(Q*2))").await;
    let payload = "中文🙂;O'Reilly\\尾'; DROP TABLE C2_TYPED; --";
    let changes = vec![("ID".into(), DbValue::Null), integer("BIG", "9223372036854775807"),
        ("AMT".into(), DbValue::Decimal("12345678901234567890.123456789012".into())), text("TXT", payload),
        ("NIL".into(), DbValue::Null), text("EMPTY", ""), ("BIN".into(), DbValue::Binary("AP8BgA==".into())),
        ("D".into(), DbValue::Date("2026-02-28".into())), ("TM".into(), DbValue::Time("12:34:00".into())),
        ("TS".into(), DbValue::Timestamp("2026-11-09 12:34:00".into())),
        ("TZ".into(), DbValue::Timestamptz("2026-11-09T12:34:56.123456789+05:30".into())),
        ("U".into(), DbValue::Uuid("12345678-1234-1234-1234-123456789abc".into()))];
    let draft = fixture.draft("C2_TYPED", "insert", vec![], vec![], changes);
    let plan = fixture.preview(&draft).await;
    assert!(plan.jdbc.is_some()); assert!(!plan.sql.contains(payload)); assert!(!plan.changes.iter().any(|(name, _)| name == "ID"));
    assert!(plan.changes.contains(&("TM".into(), DbValue::Time("12:34".into()))));
    assert!(plan.changes.contains(&("TS".into(), DbValue::Timestamp("2026-11-09T12:34".into()))));
    assert!(serde_json::to_vec(&plan).unwrap().len() > serde_json::to_vec(&plan.changes).unwrap().len(), "real full metadata counts against the shared byte budget");
    let mut baseline = plan.changes.clone(); baseline.extend(identity("1")); baseline.push(integer("Q", "7")); baseline.push(integer("G", "14"));
    let before = plan.jdbc.as_ref().unwrap().metadata.clone();
    let registry = mutation::Registry::default(); let id = registry.put(plan).unwrap();
    assert!(registry.take(&id, "different-window", OWNER).is_err());
    assert!(registry.take(&id, PRINCIPAL, "different-grid").is_err());
    let receipt = fixture.submit(&registry, &id).await;
    assert_eq!(receipt.plan_id, id); assert_eq!(receipt.status, "applied"); assert!(receipt.verified);
    assert_eq!(receipt.affected, 1); assert_eq!(receipt.transaction, "committed");
    let rows = fixture.sql("SELECT BIG,AMT,TXT,NIL,EMPTY,BIN,CAST(U AS VARCHAR) FROM C2_TYPED WHERE ID=1").await;
    assert_eq!(rows.rows.len(), 1);
    assert_eq!(rows.rows[0][0].as_deref(), Some("9223372036854775807"));
    assert_eq!(rows.rows[0][1].as_deref(), Some("12345678901234567890.123456789012"));
    assert_eq!(rows.rows[0][2].as_deref(), Some(payload)); assert!(rows.rows[0][3].is_none());
    assert_eq!(rows.rows[0][4].as_deref(), Some("")); assert_eq!(rows.rows[0][5].as_deref(), Some("base64:AP8BgA=="));
    assert_eq!(rows.rows[0][6].as_deref(), Some("12345678-1234-1234-1234-123456789abc"));
    assert_eq!(fixture.http().relational_metadata(&before.object).await.unwrap().revision, before.revision, "real row/identity changes do not change object generation");

    let noop = fixture.preview(&fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", payload)], vec![text("TXT", payload)])).await;
    let receipt = fixture.submit(&registry, &registry.put(noop).unwrap()).await;
    assert_eq!(receipt.status, "unchanged"); assert!(receipt.verified); assert_eq!(receipt.affected, 0); assert_eq!(receipt.transaction, "committed");
    let stale = fixture.preview(&fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", "loaded-stale")], vec![text("TXT", "must-not-apply")])).await;
    let receipt = fixture.submit(&registry, &registry.put(stale).unwrap()).await;
    assert_eq!(receipt.status, "conflict"); assert!(!receipt.verified); assert_eq!(receipt.affected, 0); assert_eq!(receipt.transaction, "rolled_back");
    assert_eq!(fixture.sql("SELECT TXT FROM C2_TYPED WHERE ID=1").await.rows[0][0].as_deref(), Some(payload));

    let update = fixture.preview(&fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", payload)], vec![text("TXT", "verified-new")])).await;
    let receipt = fixture.submit(&registry, &registry.put(update).unwrap()).await; assert!(receipt.verified); assert_eq!(receipt.affected, 1);
    baseline.iter_mut().find(|(name, _)| name == "TXT").unwrap().1 = DbValue::Text("verified-new".into());
    let violates = fixture.preview(&fixture.draft("C2_TYPED", "update", identity("1"), vec![integer("Q", "7")], vec![integer("Q", "-1")])).await;
    let receipt = fixture.submit(&registry, &registry.put(violates).unwrap()).await;
    assert_eq!(receipt.status, "failed"); assert!(!receipt.verified); assert_eq!(receipt.affected, 0); assert_eq!(receipt.transaction, "rolled_back");
    assert_eq!(fixture.sql("SELECT Q FROM C2_TYPED WHERE ID=1").await.rows[0][0].as_deref(), Some("7"));

    for (old, changes, expected) in [
        (vec![], vec![text("TXT", "no-baseline")], "MUTATION_BASELINE_REQUIRED"),
        (vec![integer("G", "14")], vec![integer("G", "99")], "READ_ONLY_COLUMN"),
        (vec![integer("ID", "1")], vec![integer("ID", "2")], "READ_ONLY_COLUMN"),
        (vec![("AMT".into(), DbValue::Decimal("12345678901234567890.123456789012".into()))], vec![("AMT".into(), DbValue::Decimal("1.0000000000001".into()))], "MUTATION_VALUE_INVALID"),
    ] {
        let error = mutation::prepare_plan(&fixture.db, &fixture.kind,
            &fixture.draft("C2_TYPED", "update", identity("1"), old, changes), PRINCIPAL, fixture.fingerprint.clone()).await.unwrap_err();
        assert_eq!(app_code(error), expected);
    }
    let readonly = fixture.preview(&fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", "verified-new")], vec![text("TXT", "readonly-write")])).await;
    let id = registry.put(readonly).unwrap(); let readonly = registry.take(&id, PRINCIPAL, OWNER).unwrap();
    assert_eq!(app_code(mutation::execute_plan(&fixture.db, &fixture.kind, &id, &readonly, true, 10).await.unwrap_err()), "READ_ONLY_VIOLATION");
    assert_eq!(fixture.sql("SELECT TXT FROM C2_TYPED WHERE ID=1").await.rows[0][0].as_deref(), Some("verified-new"));

    fixture.sql("CREATE TABLE C2_KEYS(ID BIGINT PRIMARY KEY,K VARCHAR(20) NOT NULL UNIQUE,V VARCHAR(20)); INSERT INTO C2_KEYS VALUES(1,'business','old')").await;
    let business = fixture.preview(&fixture.draft("C2_KEYS", "update", vec![text("K", "business")], vec![text("V", "old")], vec![text("V", "business-new")])).await;
    assert_eq!(business.keys, [text("K", "business")]);
    assert!(fixture.submit(&registry, &registry.put(business).unwrap()).await.verified);
    let changed_pk = fixture.preview(&fixture.draft("C2_KEYS", "update", identity("1"), vec![], identity("2"))).await;
    assert!(fixture.submit(&registry, &registry.put(changed_pk).unwrap()).await.verified);
    assert_eq!(fixture.sql("SELECT ID,V FROM C2_KEYS").await.rows, vec![vec![Some("2".into()), Some("business-new".into())]]);

    fixture.sql("CREATE SCHEMA C2_OTHER; CREATE TABLE C2_OTHER.C2_TYPED(ID BIGINT PRIMARY KEY,TXT VARCHAR(20)); INSERT INTO C2_OTHER.C2_TYPED VALUES(1,'other-page')").await;
    let mut other = fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", "other-page")], vec![text("TXT", "other-new")]); other.schema = "C2_OTHER".into();
    let main = fixture.draft("C2_TYPED", "update", identity("1"), vec![text("TXT", "verified-new")], vec![text("TXT", "main-page-new")]);
    let (main_plan, other_plan) = tokio::join!(fixture.preview(&main), fixture.preview(&other));
    let main_id = registry.put(main_plan).unwrap(); let other_id = registry.put(other_plan).unwrap();
    let (main_result, other_result) = tokio::join!(fixture.submit(&registry, &main_id), fixture.submit(&registry, &other_id));
    assert!(main_result.verified && other_result.verified);
    baseline.iter_mut().find(|(name, _)| name == "TXT").unwrap().1 = DbValue::Text("main-page-new".into());
    assert_eq!(fixture.sql("SELECT TXT FROM PUBLIC.C2_TYPED").await.rows[0][0].as_deref(), Some("main-page-new"));
    assert_eq!(fixture.sql("SELECT TXT FROM C2_OTHER.C2_TYPED").await.rows[0][0].as_deref(), Some("other-new"));

    fixture.sql("CREATE TABLE C2_ABA(ID BIGINT PRIMARY KEY,V VARCHAR(40)); INSERT INTO C2_ABA VALUES(1,'old')").await;
    let stale_object = fixture.preview(&fixture.draft("C2_ABA", "update", identity("1"), vec![text("V", "old")], vec![text("V", "must-not-write")])).await;
    let old_metadata = stale_object.jdbc.as_ref().unwrap().metadata.clone();
    let id = registry.put(stale_object).unwrap(); let stale_object = registry.take(&id, PRINCIPAL, OWNER).unwrap();
    fixture.sql("DROP TABLE C2_ABA; CREATE TABLE C2_ABA(ID BIGINT PRIMARY KEY,V VARCHAR(40)); INSERT INTO C2_ABA VALUES(1,'old')").await;
    let fresh_metadata = fixture.http().relational_metadata(&old_metadata.object).await.unwrap();
    assert_eq!(old_metadata.backend_object_id, fresh_metadata.backend_object_id, "actual H2 numeric ID is recycled");
    assert_eq!(old_metadata.definition, fresh_metadata.definition, "identical DDL is not an instance identity");
    assert_ne!(old_metadata.revision, fresh_metadata.revision, "real Table instance generation rejects same-name/ID/DDL ABA");
    assert_eq!(app_code(mutation::validate_plan_context(&fixture.db, &stale_object).await.unwrap_err()), "MUTATION_CONTEXT_CHANGED");
    // Also prove the actual driver's owned transaction rechecks generation when
    // recreation races after the service check: no text/native fallback exists.
    let receipt = mutation::execute_plan(&fixture.db, &fixture.kind, &id, &stale_object, false, 10).await.unwrap();
    assert_eq!(receipt.status, "conflict"); assert!(!receipt.verified); assert_eq!(receipt.affected, 0);
    assert_eq!(fixture.sql("SELECT V FROM C2_ABA WHERE ID=1").await.rows[0][0].as_deref(), Some("old"));

    let incomplete_delete = fixture.draft("C2_TYPED", "delete", identity("1"), vec![text("TXT", "main-page-new")], vec![]);
    assert_eq!(app_code(mutation::prepare_plan(&fixture.db, &fixture.kind, &incomplete_delete, PRINCIPAL, fixture.fingerprint.clone()).await.unwrap_err()), "MUTATION_BASELINE_REQUIRED");
    let deletion = fixture.preview(&fixture.draft("C2_TYPED", "delete", identity("1"), baseline, vec![])).await;
    let deletion = fixture.submit(&registry, &registry.put(deletion).unwrap()).await;
    assert!(deletion.verified); assert_eq!(deletion.affected, 1); assert_eq!(deletion.transaction, "committed");
    assert_eq!(fixture.sql("SELECT COUNT(*) FROM C2_TYPED").await.rows[0][0].as_deref(), Some("0"));
    drop(fixture);

    let unverified = new_fixture(generic, true).await;
    let denied = unverified.draft("ANY_TABLE", "insert", vec![], vec![], vec![]);
    assert_eq!(app_code(mutation::prepare_plan(&unverified.db, &unverified.kind, &denied, PRINCIPAL, unverified.fingerprint.clone()).await.unwrap_err()), "UNSUPPORTED_MUTATION");
    assert_eq!(unverified.sql("SELECT 1").await.rows[0][0].as_deref(), Some("1"), "uncertified compatibility mode still supports readonly browsing");
    println!("REAL C2 BACKEND SERVICE PASS: shared Registry owner/once/budget, exact typed/generated readback, no-op/CAS/constraints, flags/read-only/baselines, business/new keys, concurrent scopes, actual H2 ABA generation, verified full-row delete and uncertified-mode refusal");
}

