//! Opt-in tests of the Rust -> framed Java -> REAL H2 database path. They do not
//! claim desktop IPC coverage or certification of any other JDBC product/version.
use super::*;
use crate::http_db::HttpAdapter;
use crate::models::{ConnectionRequest, DbKind};

fn request(kind: &str) -> ConnectionRequest {
    let root = crate::storage::portable_root();
    assert!(root.starts_with(std::env::temp_dir()) && root.file_name().unwrap().to_string_lossy().starts_with("navkit-pl20-command-tests-"),
        "real driver tests must run a copied executable in an isolated portable root");
    let jar = std::env::var("NAVKIT_H2_JAR").expect("actual official H2 JAR required; missing dependency is NOT VERIFIED");
    ConnectionRequest { kind: DbKind::of(kind), host: String::new(), port: 0, user: "sa".into(), password: String::new(),
        database: format!("jdbc:h2:mem:pl20_rust_{};DB_CLOSE_DELAY=-1", uuid::Uuid::new_v4().simple()), file: String::new(),
        params: serde_json::json!({"h2_jar":jar}).to_string(), timeout_secs: 30 }
}
fn plan(metadata: &JdbcMetadataSnapshot, kind: &str, changes: Vec<(String, DbValue)>, keys: Vec<(String, DbValue)>, original: Vec<(String, DbValue)>) -> JdbcRowPlan {
    JdbcRowPlan { operation_id: uuid::Uuid::new_v4().to_string(), session_id: metadata.session_id.clone(), object: metadata.object.clone(),
        base_revision: metadata.revision.clone(), kind: kind.into(), changes, keys, original_values: original, read_only: false, timeout_secs: 10 }
}
fn identity() -> Vec<(String, DbValue)> { vec![("ID".into(), DbValue::Integer("1".into()))] }
async fn exercise(adapter: &dyn HttpAdapter) {
    let capabilities = adapter.relational_capabilities().await.unwrap();
    assert!(capabilities.row_write && capabilities.metadata && capabilities.transactions && !capabilities.read_only);
    assert!(!capabilities.ddl_write);
    adapter.run("PUBLIC", "", "CREATE TABLE RUST_TYPED(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,BIG BIGINT,AMT DECIMAL(38,12),TXT VARCHAR(100),NIL VARCHAR(10),EMPTY VARCHAR(10),BIN VARBINARY(64),D DATE,TM TIME(9),TS TIMESTAMP(9),TZ TIMESTAMP(9) WITH TIME ZONE,Q INTEGER DEFAULT 7 CHECK(Q>=0),G INTEGER GENERATED ALWAYS AS(Q*2))").await.unwrap();
    let object = JdbcObjectId { catalog: capabilities.catalog.clone(), schema: "PUBLIC".into(), name: "RUST_TYPED".into() };
    let metadata = adapter.relational_metadata(&object).await.unwrap();
    assert_eq!(metadata.session_id, capabilities.session_id);
    assert_eq!(metadata.primary_key, ["ID"]);
    assert!(metadata.columns.iter().any(|column| column.name == "ID" && column.auto_increment == Some(true)));
    assert!(metadata.columns.iter().any(|column| column.name == "G" && column.generated == Some(true)));
    let text = DbValue::Text("中文;O'Reilly\\尾🙂".into());
    let values = vec![("BIG".into(), DbValue::Integer("9223372036854775807".into())),
        ("AMT".into(), DbValue::Decimal("12345678901234567890.123456789012".into())), ("TXT".into(), text.clone()),
        ("NIL".into(), DbValue::Null), ("EMPTY".into(), DbValue::Text(String::new())), ("BIN".into(), DbValue::Binary("AP8BgA==".into())),
        ("D".into(), DbValue::Date("2026-02-28".into())), ("TM".into(), DbValue::Time("12:34:56.123456789".into())),
        ("TS".into(), DbValue::Timestamp("2026-11-09T12:34:56.123456789".into())),
        ("TZ".into(), DbValue::Timestamptz("2026-11-09T12:34:56.123456789+05:30".into()))];
    let receipt = adapter.apply_row_plan(&plan(&metadata, "insert", values.clone(), vec![], vec![])).await.unwrap();
    assert_eq!(receipt.status, "applied"); assert!(receipt.verified); assert_eq!(receipt.transaction, "committed");
    assert_eq!(receipt.affected_rows.as_deref(), Some("1")); assert_eq!(receipt.matched_rows.as_deref(), Some("1"));
    assert_eq!(receipt.generated_keys, identity());
    for value in &values { assert!(receipt.readback.contains(value), "lossless Rust/Java readback: {value:?}"); }
    assert!(receipt.readback.contains(&("G".into(), DbValue::Integer("14".into()))));
    assert_eq!(adapter.relational_metadata(&object).await.unwrap().revision, metadata.revision, "row/identity cursor changes cannot invalidate structural revision");
    let noop = adapter.apply_row_plan(&plan(&metadata, "update", vec![("TXT".into(), text.clone())], identity(), vec![("TXT".into(), text.clone())])).await.unwrap();
    assert_eq!(noop.status, "unchanged"); assert!(noop.verified); assert_eq!(noop.affected_rows.as_deref(), Some("0"));
    let conflict = adapter.apply_row_plan(&plan(&metadata, "update", vec![("TXT".into(), DbValue::Text("not applied".into()))], identity(), vec![("TXT".into(), DbValue::Text("stale".into()))])).await.unwrap();
    assert_eq!(conflict.status, "conflict"); assert!(!conflict.verified); assert_eq!(conflict.transaction, "rolled_back");
    assert_eq!(conflict.matched_rows.as_deref(), Some("0"));
    let mut readonly = plan(&metadata, "delete", vec![], identity(), vec![]); readonly.read_only = true;
    assert!(adapter.apply_row_plan(&readonly).await.unwrap_err().to_string().contains("READ_ONLY_VIOLATION"));
    let mut stale = plan(&metadata, "delete", vec![], identity(), vec![]); stale.session_id = uuid::Uuid::new_v4().to_string();
    assert!(adapter.apply_row_plan(&stale).await.unwrap_err().to_string().contains("STALE_CONTEXT"));
    assert_eq!(adapter.relational_capabilities().await.unwrap().session_id, capabilities.session_id);
    adapter.run("PUBLIC", "", "CREATE SCHEMA OTHER_RUST; CREATE TABLE OTHER_RUST.RUST_TYPED(ID BIGINT PRIMARY KEY,TXT VARCHAR(100)); INSERT INTO OTHER_RUST.RUST_TYPED VALUES(1,'OTHER')").await.unwrap();
    let other = JdbcObjectId { schema: "OTHER_RUST".into(), ..object.clone() };
    let (left, right) = tokio::join!(adapter.relational_metadata(&object), adapter.relational_metadata(&other));
    assert_eq!(left.unwrap().object, object); assert_eq!(right.unwrap().object, other);
    let (left, right) = tokio::join!(adapter.run("PUBLIC", "", "SELECT TXT FROM RUST_TYPED"), adapter.run("OTHER_RUST", "", "SELECT TXT FROM RUST_TYPED"));
    assert_eq!(left.unwrap().rows[0][0].as_deref(), Some("中文;O'Reilly\\尾🙂")); assert_eq!(right.unwrap().rows[0][0].as_deref(), Some("OTHER"));
    let delete = adapter.apply_row_plan(&plan(&metadata, "delete", vec![], identity(), vec![("TXT".into(), text)])).await.unwrap();
    assert!(delete.verified); assert_eq!(delete.affected_rows.as_deref(), Some("1"));
    let missing = adapter.apply_row_plan(&plan(&metadata, "delete", vec![], identity(), vec![])).await.unwrap();
    assert_eq!(missing.status, "conflict"); assert_eq!(missing.affected_rows.as_deref(), Some("0"));
    println!("REAL RUST/JAVA PL20 PASS: exact types/generated keys/owned commit/locked no-op/CAS/refusals/shared scopes/one-row delete");
}

