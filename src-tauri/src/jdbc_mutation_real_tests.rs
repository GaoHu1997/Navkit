#[tokio::test]
#[ignore = "official H2 2.3.232 + Java; copied executable and driver definitions in navkit-pl20-command-tests-* temp root"]
async fn real_saved_explicit_jdbc_binding_routes_without_native_or_odbc_fallback() {
    use crate::driver_manager::{DriverDefinition, DriverProtocol, DriverSource, PARAMS_PREFIX};
    let mut req = request("odbc");
    req.file = ":memory:".into(); // A native SQLite fallback would genuinely succeed.
    let root = crate::storage::portable_root();
    let data = crate::storage::data_dir();
    assert!(data.starts_with(&root), "never write outside this copied executable's private fixture");
    let path = data.join("drivers.json");
    let definition = DriverDefinition {
        id: format!("pl20_route_{}", uuid::Uuid::new_v4().simple()), name: "Private real H2 route fixture".into(),
        protocol: DriverProtocol::Jdbc, source: DriverSource::File,
        target: std::env::var("NAVKIT_H2_JAR").unwrap(), template: req.database.clone(),
        driver_class: "org.h2.Driver".into(), test_sql: "SELECT 1".into(),
    };
    let write_definition = |driver: &DriverDefinition| std::fs::write(&path, serde_json::to_vec(&vec![driver]).unwrap()).unwrap();
    write_definition(&definition);
    let binding = format!("{PARAMS_PREFIX}{}", serde_json::json!({"version":1,"driver_id":definition.id,"template":""}));
    req.params = binding.clone();
    let unknown = format!("pl20_unknown_{}", uuid::Uuid::new_v4().simple());
    assert!(DbKind::of(&unknown).meta().is_none());

    // A generic/uncatalogued identity with a verified explicit driver must route
    // through the REAL JVM; a known native identity must respect the same binding.
    for kind in ["odbc", unknown.as_str(), "sqlite"] {
        req.kind = DbKind::of(kind);
        let db = crate::db::open(&req).await.unwrap();
        let crate::db::Db::Http(http) = db else { panic!("explicit JDBC binding silently selected a native/ODBC adapter"); };
        let caps = http.relational_capabilities().await.unwrap();
        assert_eq!(caps.product, "H2"); assert!(caps.row_write && !caps.ddl_write);
        assert_eq!(http.run("PUBLIC", "", "SELECT 1").await.unwrap().rows[0][0].as_deref(), Some("1"));
    }

    // Saved settings admission and authoritative C2 read-only checks are not
    // waived by a binding, including the parser's documented surrounding spaces.
    req.kind = DbKind::of("sqlite"); req.params = format!("  {binding}  ");
    let mut settings = crate::models::AppSettings::default(); settings.connect_timeout_secs = 60;
    let db = crate::db::open_saved(&req, true, &settings).await.unwrap();
    let crate::db::Db::Http(http) = db else { panic!("saved whitespace binding fell back to SQLx"); };
    let caps = http.relational_capabilities().await.unwrap();
    http.run("PUBLIC", "", "CREATE TABLE ROUTE_GUARD(ID BIGINT PRIMARY KEY,TXT VARCHAR(20)); INSERT INTO ROUTE_GUARD VALUES(1,'preserved')").await.unwrap();
    let object = JdbcObjectId { catalog: caps.catalog, schema: "PUBLIC".into(), name: "ROUTE_GUARD".into() };
    let metadata = http.relational_metadata(&object).await.unwrap();
    let mut readonly = plan(&metadata, "delete", vec![], identity(), vec![]); readonly.read_only = true;
    assert!(http.apply_row_plan(&readonly).await.unwrap_err().to_string().contains("READ_ONLY_VIOLATION"));
    assert_eq!(http.run("PUBLIC", "", "SELECT TXT FROM ROUTE_GUARD WHERE ID=1").await.unwrap().rows[0][0].as_deref(), Some("preserved"));
    drop(http);
    settings.connect_timeout_secs = 0;
    assert!(settings.validate_execution_settings().is_err());
    assert!(crate::db::open_saved(&req, true, &settings).await.is_err(), "invalid saved connection budget cannot be skipped by JDBC routing");

    async fn rejects(request: &ConnectionRequest, expected: &str) {
        let error = match crate::db::open(request).await { Err(error) => error, Ok(_) => panic!("invalid binding silently opened a fallback adapter") };
        let message = format!("{error:#}"); assert!(message.contains(expected), "must reject for {expected}, not native/ODBC fallback: {message}");
    }
    req.kind = DbKind::of(&unknown); req.params.clear(); rejects(&req, "适配器尚未提供").await;
    req.kind = DbKind::of("odbc"); rejects(&req, "适配器尚未提供").await;
    req.kind = DbKind::of("sqlite");
    req.params = format!("{PARAMS_PREFIX}{{not-json"); rejects(&req, "自定义驱动连接配置损坏").await;
    req.params = format!("{PARAMS_PREFIX}{}", serde_json::json!({"version":2,"driver_id":definition.id,"template":""})); rejects(&req, "不支持的自定义驱动配置版本").await;
    req.params = format!("{PARAMS_PREFIX}{}", serde_json::json!({"version":1,"driver_id":"missing-private-driver","template":""})); rejects(&req, "自定义驱动已删除").await;
    req.params = binding.clone();
    let mut broken = definition.clone(); broken.driver_class = "pl20.driver.ThisClassMustNotExist".into(); write_definition(&broken);
    rejects(&req, "JDBC").await; // Real JVM/class loading fails; SQLite must not be tried.
    write_definition(&definition);
    req.params = format!("{PARAMS_PREFIX}{}", serde_json::json!({"version":1,"driver_id":definition.id,"template":"not-a-jdbc-url"}));
    rejects(&req, "jdbc:").await;
    println!("REAL PL20 ROUTING PASS: explicit generic/unknown/native identities, saved settings/read-only admission, missing/malformed/failed bindings never fall back");
}

