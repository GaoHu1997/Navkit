/**
 * 渲染品牌 logo。无品牌的数据源（如自定义 ODBC）返回空串，由调用方回退到线性图标。
 * opts.gray / opts.planned → 置灰；opts.className 追加类名。
 */
export function dbLogo(kind, size = 16, opts = {}) {
  const entry = DB_LOGOS[kind];
  if (!entry) return "";
  const off = opts.gray || opts.planned ? " is-off" : "";
  // ≥24px：品牌图形本身可辨，直接展示；<24px：包白色圆角画框，对齐线性图标的视觉重量
  if (size >= 24) {
    return `<img class="db-logo${off}${opts.className ? " " + opts.className : ""}" src="${entry}" width="${size}" height="${size}" alt="" draggable="false">`;
  }
  const inner = size - 6;
  return `<span class="db-logo-tile${off}${opts.className ? " " + opts.className : ""}" style="width:${size}px;height:${size}px"><img src="${entry}" width="${inner}" height="${inner}" alt="" draggable="false"></span>`;
}
